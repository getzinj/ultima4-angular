function entry(body: Body): NativeRoutine {
  return exitRoutine((machine: LiftedMachine): Ult4Monsters => new Ult4Monsters(machine), body);
}


export const ULT4_MODULE: INativeModule = {
  disk: 'program',
  name: 'ULT4',
  load: ULT4_LOAD,
  partial: true,
  install: (machine: LiftedMachine): void => {
    for (const [ address, bytes ] of [ ...ult4Data(), ...combatData(), ...spellData(), ...monsterData() ]) {
      bytes.forEach((value: number, index: number): void => machine.write(address + index, value));
    }
  },
  entries: new Map<number, NativeRoutine>([ ...BODIES, ...COMBAT_BODIES, ...SPELL_BODIES, ...MONSTER_BODIES ].map(([ address, body ]: [ number, Body ]): [ number, NativeRoutine ] => [ address, entry(body) ])),
};

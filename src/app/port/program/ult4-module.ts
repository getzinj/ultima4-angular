function entry(body: Body): NativeRoutine {
  return exitRoutine((machine: LiftedMachine): Ult4Combat => new Ult4Combat(machine), body);
}


export const ULT4_MODULE: INativeModule = {
  disk: 'program',
  name: 'ULT4',
  load: ULT4_LOAD,
  partial: true,
  install: (machine: LiftedMachine): void => {
    for (const [ address, bytes ] of [ ...ult4Data(), ...combatData() ]) {
      bytes.forEach((value: number, index: number): void => machine.write(address + index, value));
    }
  },
  entries: new Map<number, NativeRoutine>([ ...BODIES, ...COMBAT_BODIES ].map(([ address, body ]: [ number, Body ]): [ number, NativeRoutine ] => [ address, entry(body) ])),
};

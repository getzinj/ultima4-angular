// Writes src/app/state/symbols.ts from the remaster's include files:
//
//   npx nx run Ultima4:generate-symbols <checkout of sean-gugler/u4remasteredA2 at 428a793>

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { IncludeError, readIncludes } from './include-parser';
import type { IIncludeFile, ISymbol } from './include-parser';

const COMMIT: string = '428a793a4d6327cc9734ec151bf377f3d328f2cc';
const OUT: string = join(process.cwd(), 'apps/Ultima4/src/app/state/symbols.ts');


function constantName(file: string): string {
  return file.replace(/\.i$/, '').toUpperCase();
}


function literal(value: number): string {
  return (value < 0) ? String(value) : `0x${ value.toString(16).toUpperCase().padStart(value > 0xFF ? 4 : 2, '0') }`;
}


function main(checkout: string): void {
  const head: string = execFileSync('git', [ '-C', checkout, 'rev-parse', 'HEAD' ], { encoding: 'utf8' }).trim();

  if (head !== COMMIT) {
    throw new IncludeError(`${ checkout } is at ${ head }; the generator is pinned to ${ COMMIT }`);
  } else {
    const directory: string = join(checkout, 'src/include');
    const files: IIncludeFile[] = readdirSync(directory).filter((name: string): boolean => name.endsWith('.i')).sort()
      .map((name: string): IIncludeFile => ({ name, text: readFileSync(join(directory, name), 'latin1') }));
    const symbols: Map<string, ISymbol[]> = readIncludes(files, 'uscii.i');
    const sections: string[] = Array.from(symbols)
      .filter(([ , list ]: [ string, ISymbol[] ]): boolean => list.length > 0)
      .map(([ file, list ]: [ string, ISymbol[] ]): string => [
        `/** \`${ file }\` */`,
        `export const ${ constantName(file) } = {`,
        ...list.map((symbol: ISymbol): string => `  ${ symbol.name }: ${ literal(symbol.value) },`),
        '} as const;',
      ].join('\n'));

    writeFileSync(OUT, [
      `// Generated by apps/Ultima4/tools/symbols/generate-symbols.ts from sean-gugler/u4remasteredA2 (fixed, ${ COMMIT.slice(0, 7) }),`,
      '// src/include/*.i. Do not edit: rerun the generator. The names are Sean Gugler\'s (CC BY-SA 4.0, see NOTICE).',
      '// Character constants are as the game assembles them, through uscii.i\'s charmap.',
      '',
      sections.join('\n\n\n'),
      '',
    ].join('\n'));
    console.log(`${ OUT }: ${ sections.length } files, ${ Array.from(symbols.values()).flat().length } symbols`);
  }
}


main(process.argv[2]);
